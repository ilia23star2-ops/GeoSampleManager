package com.example.geosamplemanager.ui.screens.admin

/**
 * FIX 5.10-stat-admin-password:
 * Проверка пароля на вход в панель администратора.
 *
 * Цель — не защита от взлома (APK всё равно разбирается), а
 * «ОП случайно не откроет». Реальный админ знает пароль из
 * памятки.
 *
 * Решения:
 *  - У1=А: пароль-константа в коде (хардкод);
 *  - У2=А: пароль по умолчанию — «0000»;
 *  - У3=А: смена пароля через UI не реализуется.
 */
object AdminPanelAuth {

    /** Пароль по умолчанию. Меняется только правкой константы. */
    const val DEFAULT_PASSWORD = "0000"

    /**
     * Проверка введённого пароля. Trim от пробелов — защита от
     * случайного пробела. Регистр не важен (пароль только из
     * цифр, но на всякий случай).
     */
    fun checkPassword(input: String): Boolean {
        return input.trim() == DEFAULT_PASSWORD
    }
}