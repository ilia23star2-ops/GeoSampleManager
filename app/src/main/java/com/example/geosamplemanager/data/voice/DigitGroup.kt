package com.example.geosamplemanager.data.voice

/**
 * FIX 5.8.11-c (SEARCH_MODEL §5.2):
 * Группа цифр — единица модели числа.
 *
 * Сохраняет структуру ввода пользователя:
 *   «109 00 31» → три группы [PLAIN("109"), LEADING_ZERO("00"), PLAIN("31")]
 *   «1090031»   → одна группа [PLAIN("1090031")]
 *
 * Используется:
 *   - для построения кандидатов поиска (GroupToCandidates, заход c2);
 *   - для озвучки номера (VoiceSpeaker.spellOut(groups), заход c2).
 *
 * Ключевое отличие от «просто строки»: при озвучке «109 00 31» ГП
 * произносит «сто девять, ноль ноль, тридцать один» — по структуре,
 * а не рубит слитную строку на пары слева направо (Б2б).
 */
data class DigitGroup(
    /** Цифры или префикс, как в вводе: «109», «00», «KPD». */
    val value: String,
    /** Тип группы. */
    val kind: GroupKind,
    /** Исходный текст, если пришёл голосом: «сто девять». Null для ручного. */
    val sourceText: String? = null
)

/**
 * Тип группы цифр.
 *
 * PLAIN       — обычная числовая группа (1–3 цифры, без ведущего нуля).
 * LEADING_ZERO — группа нулей: «00», «000».
 * PREFIX      — латинский префикс участка: KPD, NV, ACD.
 * SINGLE      — одиночная цифра (0–9), не слившаяся с другими.
 */
enum class GroupKind {
    PLAIN,
    LEADING_ZERO,
    PREFIX,
    SINGLE
}
