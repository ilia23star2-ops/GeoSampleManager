package com.example.geosamplemanager.data.voice

/**
 * FIX 5.8.11-b (SEARCH_MODEL §4.2):
 * Нормализация строки запроса перед токенизацией.
 *
 * Шаги (по порядку):
 *   1. lowercase         — «КПД-109» → «кпд-109»
 *   2. ё → е             — «трёхсот» → «трехсот»
 *   3. trim              — обрезать пробелы по краям
 *   4. дефисы → пробелы  — «15-24» → «15 24»
 *   5. жёсткие знаки (,;:!?) → пробелы
 *   6. точка в конце → убрать (но не в середине — десятичные!)
 *   7. сжать пробелы     — «15  24» → «15 24»
 *
 * Не трогает структуру: «109 00 31» остаётся тремя токенами,
 * а не превращается в «1090031».
 *
 * Используется и ручным вводом, и голосовым — в этом весь смысл.
 */
object QueryNormalizer {

    private val MULTI_SPACE = Regex("\\s+")
    private val HARD_PUNCT = Regex("[,;:!?]")

    /**
     * Привести строку к нормализованному виду.
     * Возвращает пустую строку, если на входе пусто.
     */
    fun normalize(input: String): String {
        if (input.isBlank()) return ""

        var s = input
            .lowercase()
            .replace('ё', 'е')
            .trim()

        // Дефисы → пробелы: «15-24» → «15 24»
        s = s.replace('-', ' ')

        // Жёсткие знаки → пробелы: «1524,1525» → «1524 1525»
        s = s.replace(HARD_PUNCT, " ")

        // Точка только в конце строки: «1524.» → «1524».
        // В середине не трогаем — это десятичный разделитель: «2.6».
        s = s.trimEnd('.')

        // Сжимаем пробелы
        s = s.replace(MULTI_SPACE, " ")

        return s.trim()
    }
}
