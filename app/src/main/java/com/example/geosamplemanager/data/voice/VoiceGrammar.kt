/**
 * Сборщик JSON-грамматики для Vosk.
 *
 * Грамматика — это список слов, которые Vosk может распознать.
 * Всё, что не в списке, — не распознаётся (заменяется на [unk]).
 *
 * Зачем: маленькая модель Vosk путается между похожими словами
 * («ноля» → «нала» → «налёт»). Ограничение словаря резко повышает
 * точность на числах.
 *
 * FIX 5.8.6-1:
 * Добавлены слова для новых голосовых сценариев:
 * - выбор действия: «снять», «отложить», «пропустить»;
 * - русский вес: «целых», «десятых», «сотых», «половиной», «полтора», «полкило»;
 * - служебные фразы: «сколько осталось», «показать отложенные», «снять последнюю».
 *
 * FIX 5.8.11-e4g3:
 * Добавлены глаголы явного поиска — «найди», «найти», «ищи», «искать»,
 * «поищи». Распознаются в VoiceCommandParser как VoiceCommand.Find.
 *
 * FIX 5.8.11-e4-fix-1:
 * Убрано слово «четвертью» из грамматики. Vosk тянулся к знакомому
 * «четвертью» при произнесении порядкового «четвёртая» — команда
 * отметки ломалась. Пользователь подтвердил: форму «с четвертью»
 * в работе никто не использует. Оставлены «с половиной», «полтора».
 */
